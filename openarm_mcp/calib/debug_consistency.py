def make_T(xyz, rpy_deg):
    T = np.eye(4)
    T[:3,:3] = Rot.from_euler('xyz', rpy_deg, degrees=True).as_matrix()
    T[:3, 3] = xyz
    return T

def inv_T(T):
    Ti = np.eye(4)
    Ti[:3,:3] = T[:3,:3].T
    Ti[:3, 3] = -T[:3,:3].T @ T[:3,3]
    return Ti

