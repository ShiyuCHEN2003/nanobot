T_cb_list = [np.array(T) for T in T_cb_list]

# 用6DOF优化直接求 T_base_cam，最小化 T_ee_board 的方差
def cost(params):
    # params: [rx, ry, rz, tx, ty, tz]
    R_bc = R.from_rotvec(params[:3]).as_matrix()
    t_bc = params[3:]
    T_bc = np.eye(4)
    T_bc[:3,:3] = R_bc
    T_bc[:3, 3] = t_bc
    
    ts = []
    for T_be, T_cb in zip(T_be_list, T_cb_list):
        T_eb = inv_T(T_be)
        T_eb_board = T_eb @ T_bc @ T_cb
        ts.append(T_eb_board[:3,3])
    ts = np.array(ts)
    return np.sum(np.var(ts, axis=0))

# 用标定结果作为初始值
import json
with open("calib_handeye_chest.json") as f:
    cal = json.load(f)
T0 = np.array(cal["T_base_cam"])
r0 = R.from_matrix(T0[:3,:3]).as_rotvec()
t0 = T0[:3,3]
x0 = np.concatenate([r0, t0])

print("优化中...")
res = minimize(cost, x0, method='Nelder-Mead', 
               options={'maxiter':100000, 'xatol':1e-6, 'fatol':1e-8})

R_opt = R.from_rotvec(res.x[:3]).as_matrix()
t_opt = res.x[3:]
T_base_cam_opt = np.eye(4)
T_base_cam_opt[:3,:3] = R_opt
T_base_cam_opt[:3, 3] = t_opt

